import { apiFetch } from '../../services/api'

import { useEffect, useState } from 'react'
import { useLocation, useNavigate } from 'react-router-dom'
import {
  ArrowLeft, BrainCircuit, CheckCircle2,
  AlertTriangle, Activity, Image as ImageIcon,
  Loader2, RefreshCw
} from 'lucide-react'

interface AnalysisState {
  patientId?: string
  file?: File
  fileName?: string
  studyId?: string
  uploadResult?: {
    study_id?: string
    status?: string
  }
}

interface Prediction {
  study_id: string
  patient_id: string
  prediction: string
  confidence: number
  probabilities: {
    Normal: number
    Abnormal: number
  }
  model: string
  clinical_status: string
}

const API_URL = 'http://127.0.0.1:8000'

export default function AnalysisResults() {
  const navigate = useNavigate()
  const location = useLocation()
  const state = (location.state || {}) as AnalysisState

  const studyId = state.studyId || state.uploadResult?.study_id

  const [result, setResult] = useState<Prediction | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const runPrediction = async () => {
    if (!studyId) {
      setError('Study ID is missing. Please upload the MRI again.')
      setLoading(false)
      return
    }

    setLoading(true)
    setError('')
    setResult(null)

    try {
      const response = await apiFetch(
        `${API_URL}/api/studies/${encodeURIComponent(studyId)}/predict`,
        { method: 'POST' }
      )

      const data = await response.json()

      if (!response.ok) {
        throw new Error(data.detail || 'Prediction failed.')
      }

      setResult(data as Prediction)
    } catch (err) {
      setError(
        err instanceof Error
          ? err.message
          : 'Could not connect to the prediction service.'
      )
    } finally {
      setLoading(false)
    }
  }

  useEffect(() => {
    void runPrediction()
  }, [studyId])

  const isAbnormal = result?.prediction === 'Abnormal'

  return (
    <div className="max-w-7xl mx-auto space-y-6">
      <button
        onClick={() => navigate(-1)}
        className="flex items-center gap-2 text-slate-500 hover:text-blue-600"
      >
        <ArrowLeft size={18} />
        Back
      </button>

      <div>
        <div className="flex items-center gap-2 text-xs font-semibold tracking-wider text-slate-400">
          <span>WORKSPACE</span>
          <span>/</span>
          <span>MRI ANALYSIS</span>
          <span>/</span>
          <span className="text-blue-600">RESULTS</span>
        </div>
        <h1 className="text-2xl font-bold text-slate-800 mt-2">
          MRI Analysis Results
        </h1>
        <p className="text-slate-500 mt-1">
          Experimental classification generated by the trained deep learning model.
        </p>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
        <div className="bg-white rounded-2xl border border-slate-200 p-5">
          <p className="text-sm text-slate-500">Patient ID</p>
          <p className="text-lg font-bold text-slate-800 mt-3 break-all">
            {state.patientId || result?.patient_id || 'Not provided'}
          </p>
        </div>

        <div className="bg-white rounded-2xl border border-slate-200 p-5">
          <p className="text-sm text-slate-500">Selected scan</p>
          <div className="flex items-center gap-2 mt-3">
            <ImageIcon size={20} className="text-cyan-600" />
            <p className="font-semibold text-slate-800 break-all">
              {state.file?.name || state.fileName || 'Uploaded MRI'}
            </p>
          </div>
        </div>

        <div className="bg-white rounded-2xl border border-slate-200 p-5">
          <p className="text-sm text-slate-500">Model status</p>
          <p className="text-lg font-bold text-emerald-600 mt-3">
            {result ? 'MODEL_LOADED' : loading ? 'PROCESSING' : 'CHECK REQUIRED'}
          </p>
        </div>
      </div>

      <div className="bg-white rounded-2xl border border-slate-200 p-6">
        <div className="flex items-center justify-between flex-wrap gap-3 mb-6">
          <div>
            <h2 className="text-lg font-bold text-slate-800">Processing pipeline</h2>
            <p className="text-sm text-slate-500 mt-1">
              Upload, preprocessing and inference workflow.
            </p>
          </div>
          <span className={`px-3 py-1.5 rounded-full text-xs font-semibold ${
            result
              ? 'bg-emerald-50 text-emerald-700'
              : loading
                ? 'bg-blue-50 text-blue-700'
                : 'bg-red-50 text-red-700'
          }`}>
            {result ? 'Completed' : loading ? 'Running inference' : 'Needs attention'}
          </span>
        </div>

        <div className="space-y-5">
          {[
            { title: 'File upload', description: 'MRI file received by the backend.' },
            { title: 'Image preprocessing', description: 'Grayscale conversion, resizing and normalization.' },
            { title: 'Deep learning inference', description: 'Classification using trained ResNet18 weights.' }
          ].map((step, index) => {
            const completed = Boolean(result)
            const active = loading && index === 2

            return (
              <div key={step.title} className="flex gap-4 items-start">
                <div className={`w-11 h-11 shrink-0 rounded-xl flex items-center justify-center ${
                  completed ? 'bg-emerald-50 text-emerald-600' :
                  active ? 'bg-blue-50 text-blue-600' :
                  'bg-slate-100 text-slate-400'
                }`}>
                  {completed ? <CheckCircle2 size={21} /> :
                   active ? <Loader2 size={21} className="animate-spin" /> :
                   <Activity size={21} />}
                </div>
                <div className="flex-1 border-b border-slate-100 pb-5">
                  <h3 className="font-semibold text-slate-800">
                    {index + 1}. {step.title}
                  </h3>
                  <p className="text-sm text-slate-500 mt-1">{step.description}</p>
                </div>
              </div>
            )
          })}
        </div>
      </div>

      <div className="bg-white rounded-2xl border border-slate-200 p-6">
        <div className="flex items-center gap-3 mb-6">
          <div className="p-2 rounded-lg bg-blue-50 text-blue-600">
            <BrainCircuit size={22} />
          </div>
          <div>
            <h2 className="font-bold text-slate-800">Classification output</h2>
            <p className="text-xs text-slate-400">ResNet18 deep learning model</p>
          </div>
        </div>

        {loading && (
          <div className="rounded-xl bg-blue-50 p-8 text-center">
            <Loader2 size={32} className="mx-auto text-blue-600 animate-spin mb-3" />
            <h3 className="font-semibold text-slate-800">Running model inference...</h3>
            <p className="text-sm text-slate-500 mt-2">
              Please wait while the uploaded image is processed.
            </p>
          </div>
        )}

        {error && !loading && (
          <div className="rounded-xl bg-red-50 border border-red-200 p-6">
            <p className="font-semibold text-red-800">{error}</p>
            <button
              onClick={() => void runPrediction()}
              className="mt-4 inline-flex items-center gap-2 rounded-lg bg-red-600 text-white px-4 py-2 text-sm font-semibold"
            >
              <RefreshCw size={16} /> Retry prediction
            </button>
          </div>
        )}

        {result && !loading && (
          <div className="space-y-6">
            <div className={`rounded-xl p-6 border ${
              isAbnormal
                ? 'bg-amber-50 border-amber-200'
                : 'bg-emerald-50 border-emerald-200'
            }`}>
              <p className="text-sm text-slate-600">Predicted class</p>
              <h3 className={`text-3xl font-bold mt-2 ${
                isAbnormal ? 'text-amber-700' : 'text-emerald-700'
              }`}>
                {result.prediction}
              </h3>
              <p className="text-sm text-slate-600 mt-2">
                Model confidence: <strong>{result.confidence.toFixed(2)}%</strong>
              </p>
            </div>

            <div>
              <h3 className="font-semibold text-slate-800 mb-4">
                Class probability distribution
              </h3>

              {(['Normal', 'Abnormal'] as const).map(label => (
                <div key={label} className="mb-5">
                  <div className="flex justify-between text-sm mb-2">
                    <span className="font-medium text-slate-700">{label}</span>
                    <span className="font-semibold text-slate-800">
                      {result.probabilities[label].toFixed(2)}%
                    </span>
                  </div>
                  <div className="h-3 rounded-full bg-slate-100 overflow-hidden">
                    <div
                      className={`h-full rounded-full ${
                        label === 'Normal' ? 'bg-emerald-500' : 'bg-amber-500'
                      }`}
                      style={{ width: `${result.probabilities[label]}%` }}
                    />
                  </div>
                </div>
              ))}
            </div>

            <div className="text-sm text-slate-500">
              <p>Model: <strong>{result.model}</strong></p>
              <p className="break-all">Study ID: {result.study_id}</p>
            </div>
          </div>
        )}

        <div className="mt-6 rounded-xl bg-cyan-50 border border-cyan-100 p-5">
          <div className="flex gap-3 items-start">
            <Activity size={21} className="text-cyan-700 shrink-0" />
            <div>
              <h3 className="font-semibold text-cyan-900">Explainability</h3>
              <p className="text-sm text-cyan-800 mt-1">
                Grad-CAM visualization has not yet been implemented.
              </p>
            </div>
          </div>
        </div>
      </div>

      <div className="bg-amber-50 border border-amber-200 rounded-xl p-5 flex gap-3 items-start">
        <AlertTriangle className="text-amber-600 shrink-0 mt-0.5" size={20} />
        <div>
          <h3 className="font-semibold text-amber-900">Research prototype only</h3>
          <p className="text-sm text-amber-800 mt-1">
            This experimental model output is not a medical diagnosis and must not
            be used for clinical decisions. Its evaluation used an image-level split;
            patient-level independence has not been verified. The dataset labels
            and model require further independent validation.
          </p>
        </div>
      </div>
    </div>
  )
}

